"""
make_kat.py — Deterministic WOTS+ Known-Answer Test (KAT) vector generator
=========================================================================

Produces a fixed, reproducible WOTS+ test vector for the research prototype
described in paper.md (n=32, w=16, unkeyed prefix-separated SHA-256).

The key material is generated by a SHA-256 counter-mode DRBG seeded with the
fixed string ``HBS-PQ-WOTS-KAT-v1-2026`` (as documented in the paper's
Appendix A), so the output is byte-for-byte reproducible across runs and
machines.

Output: ``kat_wots.json`` with sk / pk / sig (each 2,144 B = 67 x 32 B).

NOTE: This prototype is NON-CONFORMANT with FIPS 205; the vector is for
self-consistency / tamper checks only, not for cross-implementation KAT.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from wots import WOTSKeyPair, LEN, N, W, chain

SEED_STR = "HBS-PQ-WOTS-KAT-v1-2026"
MESSAGE_HEX = ("506f73742d7175616e74756d207369676e6174757265"
               "204b415420766563746f72202330")  # "Post-quantum signature KAT vector #0"


def drbg(seed_str: str, n_bytes: int) -> bytes:
    """SHA-256 counter-mode DRBG: block_i = SHA-256(K || i), K = SHA-256(seed)."""
    k = hashlib.sha256(seed_str.encode("utf-8")).digest()
    out = b""
    ctr = 0
    while len(out) < n_bytes:
        out += hashlib.sha256(k + ctr.to_bytes(4, "big")).digest()
        ctr += 1
    return out[:n_bytes]


def main() -> None:
    msg = bytes.fromhex(MESSAGE_HEX)
    raw = drbg(SEED_STR, LEN * N)
    sk = [raw[i * N:(i + 1) * N] for i in range(LEN)]
    # Build the public key the way WOTSKeyPair.generate() would, but from the
    # DRBG-derived secrets instead of os.urandom.
    pk = [chain(s, 0, W - 1) for s in sk]
    kp = WOTSKeyPair(sk=sk, pk=pk)
    sig = kp.sign(msg)

    assert WOTSKeyPair.verify(msg, sig, pk), "generated KAT fails self-verify"

    out = {
        "seed": SEED_STR,
        "algorithm": "WOTS+ research prototype (n=32, w=16, unkeyed SHA-256)",
        "message_hex": MESSAGE_HEX,
        "message_str": msg.decode("ascii"),
        "len": LEN,
        "n": N,
        "w": W,
        "sk": [x.hex() for x in sk],
        "pk": [x.hex() for x in pk],
        "sig": [x.hex() for x in sig],
        "sizes_bytes": {"sk": LEN * N, "pk": LEN * N, "sig": LEN * N},
    }

    out_path = Path(__file__).resolve().parent / "kat_wots.json"
    out_path.write_text(json.dumps(out, indent=2))
    print(f"[ok] KAT verified; wrote {out_path}")
    print(f"     pk[:128 bytes] = {out['pk'][0][:256]}")
    print(f"     sig[:128 bytes] = {out['sig'][0][:256]}")


if __name__ == "__main__":
    main()
